import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score, recall_score, precision_score, classification_report
from google.colab import drive

#putting the file in my drive
drive.mount('/content/drive')
bank = pd.read_csv("/content/drive/MyDrive/bank.csv")

#numerical kardane label target
bank['deposit'] = bank['deposit'].map({'yes': 1, 'no': 0})

#
for col in bank.columns:
    if bank[col].dtype == 'object':
        bank[col] = LabelEncoder().fit_transform(bank[col])

trainX, testX, trainY, testY = train_test_split(bank.drop("deposit", axis=1), bank["deposit"], random_state=256)

decisionTreeModel = DecisionTreeClassifier(random_state=50)
decisionTreeModel.fit(trainX, trainY)

predictionY = decisionTreeModel.predict(testX)

print(f"Accuracy result: {accuracy_score(testY, predictionY)}")
print(f"Precision result: {precision_score(testY, predictionY, zero_division=0)}")
print(f"Recall result: {recall_score(testY, predictionY, zero_division=0)}")
print("Report baraye Classification:")
print(classification_report(testY, predictionY))

parameters = [
    {"max_depth": 5, "min_samples_split": 0.1},
    {"max_depth": 15, "min_samples_split": 0.3},
]

for parameter in parameters:
    decisionTreeModel = DecisionTreeClassifier(random_state=45, **parameter)
    decisionTreeModel.fit(trainX, trainY)
    predictionY = decisionTreeModel.predict(testX)

    print(f"Params: {parameter}")
    print(f"Accuracy res: {accuracy_score(testY, predictionY)}")
    print(f"Precision res: {precision_score(testY, predictionY, zero_division=0)}")
    print(f"Recall res: {recall_score(testY, predictionY, zero_division=0)}")

import time
from sklearn.ensemble import RandomForestClassifier

startTime = time.time()
randomForestModel = RandomForestClassifier(n_estimators=100, random_state=55)
randomForestModel.fit(trainX, trainY)
trainTime = time.time() - startTime
randomForestPredictionY = randomForestModel.predict(testX)

print("results:")
print(f"Accuracy res: {accuracy_score(testY, randomForestPredictionY)}")
print(f"Precision res: {precision_score(testY, randomForestPredictionY, zero_division=0)}")
print(f"Recall res: {recall_score(testY, randomForestPredictionY, zero_division=0)}")
print(f"Training Time: {trainTime} secs")